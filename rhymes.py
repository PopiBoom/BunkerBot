_MAP: dict[str, list[str]] = {}
for keys, answers in _TABLE:
    for k in keys:
        _MAP[k] = answers

_last: dict[int, str] = {}


def _norm(text: str) -> str:
    t = (text or "").lower().replace("ё", "е")
    t = re.sub(r"[^\w\s]", " ", t)      # знаки, смайлы
    return re.sub(r"\s+", " ", t).strip()


def matches(text: str) -> bool:
    t = _norm(text)
    return bool(t) and len(t.split()) <= 3 and t in _MAP


def rhyme_for(text: str, chat_id: int = 0) -> str | None:
    """Рифма на всю реплику целиком (максимум три слова) или None. Не повторяет прошлую в этом чате."""
    t = _norm(text)
    if not t or len(t.split()) > 3:
        return None
    answers = _MAP.get(t)
    if not answers:
        return None
    pool = [a for a in answers if a != _last.get(chat_id)] or answers
    pick = random.choice(pool)
    _last[chat_id] = pick
    return pick
