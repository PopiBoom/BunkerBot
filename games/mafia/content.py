def mafia_count(players: int) -> int:
    if players < 6:
        return 1
    if players < 9:
        return 2
    if players < 12:
        return 3
    return 4


def deal_roles(players: int) -> list[str]:
    """Набор ролей на партию (не перемешан): классика — мафия (с Доном от двух), Комиссар, Доктор, мирные."""
    m = mafia_count(players)
    roles = ["don"] + ["mafia"] * (m - 1) if m >= 2 else ["mafia"]
    roles += ["sheriff", "doctor"]
    return roles + ["civ"] * max(0, players - len(roles))


def _plural(n: int, one: str, few: str, many: str) -> str:
    if n % 10 == 1 and n % 100 != 11:
        return one
    return few if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14 else many


def composition(roles: list[str]) -> str:
    """«2 мафии (с Доном), Комиссар, Доктор, 4 мирных»."""
    m = sum(1 for r in roles if team(r) == "mafia")
    civ = roles.count("civ")
    parts = [f"{m} {_plural(m, 'мафия', 'мафии', 'мафий')}" + (" (с Доном)" if "don" in roles else "")]
    if "sheriff" in roles:
        parts.append("Комиссар")
    if "doctor" in roles:
        parts.append("Доктор")
    if civ:
        parts.append(f"{civ} {_plural(civ, 'мирный', 'мирных', 'мирных')}")
    return ", ".join(parts)


def composition_list(roles: list[str]) -> str:
    """Состав столбиком — для лобби и обложки."""
    m = sum(1 for r in roles if team(r) == "mafia")
    civ = roles.count("civ")
    rows = [f"• Мафия — {m}" + (", из них Дон" if "don" in roles else "")]
    if "sheriff" in roles:
        rows.append("• Комиссар")
    if "doctor" in roles:
        rows.append("• Доктор")
    if civ:
        rows.append(f"• Мирные — {civ}")
    return "\n".join(rows)


