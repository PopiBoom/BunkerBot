def fallback_chance(revealed_text: str) -> tuple[int, str]:
    """Шанс погибнуть (%) по открытым картам и короткая причина."""
    t = revealed_text.lower()
    good = [w for w in _SAFER if w in t]
    bad = [w for w in _RISKIER if w in t]
    chance = 45 - 12 * len(good) + 12 * len(bad) + random.randint(-5, 5)
    chance = max(5, min(95, chance))
    if good and not bad:
        why = "есть полезные навыки"
    elif bad and not good:
        why = "здоровье и страхи против"
    elif good and bad:
        why = "навыки есть, но и слабости тоже"
    else:
        why = "о нём пока мало известно"
    return chance, why



