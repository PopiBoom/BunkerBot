def deal_actions(n: int) -> list[str]:
    """Карты действий на n игроков: по возможности без повторов."""
    ids = list(ACTIONS)
    out: list[str] = []
    while len(out) < n:
        random.shuffle(ids)
        out.extend(ids)
    return out[:n]


# ---------- тайные цели ----------


def make_goal(user_id: int, others: list[tuple[int, str]]) -> dict:
    """Тайная цель игрока. others — (user_id, имя) остальных игроков."""
    if not others:
        return {"kind": "survive", "text": "Попади в бункер любой ценой."}
    target_id, target_name = random.choice(others)
    kind = random.choice(["with", "with", "against", "survive"])
    if kind == "with":
        return {"kind": "with", "target": target_id,
                "text": f"Попади в бункер вместе с «{target_name}»."}
    if kind == "against":
        return {"kind": "against", "target": target_id,
                "text": f"Сделай так, чтобы «{target_name}» НЕ попал(а) в бункер."}
    return {"kind": "survive", "text": "Попади в бункер любой ценой."}


def goal_done(goal: dict, me_alive: bool, alive_ids: set[int]) -> bool:
    kind = goal.get("kind")
    if kind == "with":
        return me_alive and goal.get("target") in alive_ids
    if kind == "against":
        return goal.get("target") not in alive_ids
    return me_alive


