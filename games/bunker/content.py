def titles(stats: dict) -> list[tuple[str, str, str]]:
    """Звания игрока по его статистике: [(эмодзи, звание, за что)]."""
    out = []
    for emoji, name, cond, why in TITLES:
        try:
            if cond(stats):
                out.append((emoji, name, why))
        except (KeyError, ZeroDivisionError, TypeError):
            continue
    return out
