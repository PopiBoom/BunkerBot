def deal_actions(n: int) -> list[str]:
    """Карты действий на n игроков: по возможности без повторов."""
    ids = list(ACTIONS)
    out: list[str] = []
    while len(out) < n:
        random.shuffle(ids)
        out.extend(ids)
    return out[:n]


