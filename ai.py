# Шаблонные обороты «суда» — ИИ лепил их в каждое дело (владелец 08.11: «однообразно»)
_COURT_CLICHES = ("в особо крупном", "с отягчающими", "группой лиц", "с последующим", "в составе", "по предварительному")


def court_title(title: str) -> str:
    """Название статьи без номера («Ст. 2 ·» ставит код) и без шаблонного хвоста: «Нытьё о недосыпе в особо
    крупном» → «Нытьё о недосыпе»."""
    title = re.sub(r"^\s*(?:ст\.?|статья)\s*\d+[\s.·:—-]*", "", title, flags=re.IGNORECASE).strip()
    low = title.lower()
    for c in _COURT_CLICHES:
        i = low.find(c)
        if i > 0 and len(title[:i].split()) >= 2:
            title, low = title[:i].rstrip(" ,-—"), low[:i].rstrip(" ,-—")
    return title


