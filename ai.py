# Claude вызываем как обычно, через SDK Anthropic. Модель с «/» в названии (x-ai/grok-4.7,
# openai/gpt-6.1-terra-pro…) — это OpenRouter: один ключ OPENROUTER_API_KEY на сотни моделей.

OPENROUTER_URL = "https://openrouter.ai/api/v1/chat/completions"


_openrouter_key = ""  # ключ из базы бота (команда /setkey) — когда его нет в .env


def set_openrouter_key(key: str) -> None:
    global _openrouter_key
    _openrouter_key = (key or "").strip()


def openrouter_key() -> str:
    return os.getenv("OPENROUTER_API_KEY", "").strip() or _openrouter_key


def openrouter_available() -> bool:
    return bool(openrouter_key())


def is_openrouter(model: str | None) -> bool:
    return bool(model) and "/" in model


async def _complete_openrouter(system: str, user: str, model: str, max_tokens: int = 8000,
                               audio: tuple[bytes, str] | None = None) -> str:
    """Один запрос к модели через OpenRouter (их API совместим с OpenAI chat completions).
    audio — (байты, формат «wav»/«mp3»): звук в том же сообщении, что и текст (для расшифровки речи)."""
    import aiohttp

    key = openrouter_key()
    if not key:
        raise AIUnavailable("ключ OpenRouter не задан (.env или /setkey)")
    content: str | list = user
    if audio is not None:
        import base64

        content = [{"type": "text", "text": user},
                   {"type": "input_audio", "input_audio": {"data": base64.standard_b64encode(audio[0]).decode(),
                                                           "format": audio[1]}}]
    body = {
        "model": model,
        "max_tokens": max_tokens,
        "messages": [{"role": "system", "content": system}, {"role": "user", "content": content}],
        "usage": {"include": True},  # вернёт стоимость запроса в долларах — для «Расходов ИИ»
    }
    headers = {"Authorization": f"Bearer {key}", "X-Title": "BunkerBot"}
    async with aiohttp.ClientSession(timeout=aiohttp.ClientTimeout(total=180), trust_env=True) as s:
        async with s.post(OPENROUTER_URL, json=body, headers=headers) as r:
            data = await r.json(content_type=None)
            if r.status != 200 or "error" in data:
                err = (data.get("error") or {}).get("message") if isinstance(data, dict) else data
                raise AIUnavailable(f"OpenRouter {r.status}: {err}")
    usage = data.get("usage") or {}
    tin, tout = int(usage.get("prompt_tokens") or 0), int(usage.get("completion_tokens") or 0)
    cost = float(usage.get("cost") or 0.0)
    kind = _kind()
    logger.info("AI %s [%s]: in=%s out=%s ≈ $%.4f", model, kind, tin, tout, cost)
    if _usage_sink:
        try:
            await _usage_sink(current_game.get(), model, tin, tout, cost, kind)
        except Exception as e:
            logger.warning("usage sink failed: %s", e)
    choice = (data.get("choices") or [{}])[0]
    text = str((choice.get("message") or {}).get("content") or "").strip()
    if not text:  # всё ушло на «размышления» или модель промолчала — пусть вызывающий увидит ошибку
        raise AIUnavailable(f"{model} вернула пустой ответ (finish={choice.get('finish_reason')})")
    return text


