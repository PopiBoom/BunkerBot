async def update_dossier(name: str, old: str, new_messages: list) -> str:
    """Досье человека: только факты из его же сообщений, каждый — с датой и короткой дословной цитатой.

    new_messages — [(текст, ts)] (или просто тексты). Пишет Sonnet: Haiku сжимал «своими словами» и путал
    факты и людей — бот потом стебал за то, чего не было (жалоба владельца).
    """
    from datetime import datetime, timedelta, timezone

    msk = timezone(timedelta(hours=3))
    lines = []
    for m in new_messages:
        text, ts = (m if isinstance(m, (tuple, list)) else (m, None))
        date = datetime.fromtimestamp(ts, msk).strftime("%d.%m") if ts else ""
        lines.append(f'<msg date="{date}">{str(text)[:300]}</msg>')
    user = (
        f"Участник: {name}\n"
        f"Старое досье (могло быть неточным — оставь из него только то, что не противоречит новым сообщениям; "
        f"выполненные или устаревшие планы убери):\n<dossier>{old or 'пусто'}</dossier>\n"
        f"Новые сообщения ЭТОГО участника:\n" + "\n".join(lines) + "\n\n"
        "Составь досье: до 10 пунктов «- факт (дата: «короткая дословная цитата»)». Факт — то, за что можно "
        "подколоть: обещание или план со сроком, хвастовство, противоречие (говорил одно — сделал другое), "
        "позиция или мнение, привычка, которая видна в НЕСКОЛЬКИХ сообщениях, коронная фраза. Пропусти мелочь: "
        "одиночные слова («Водка», «Кидок»), стикеры, реакции, бытовуху («где тарелки», «иди на 1»). "
        "Только то, что прямо видно в его словах: не обобщай («пьёт водку» из одного «Водка»), не делай выводов о "
        "характере, не приписывай ему слова других (цитирует или пересказывает кого-то — не его факт). Сленг, мемы "
        "и непонятные фразы («кинн трек», «вписон», «на соляге») не толкуй — если не уверен, что это значит, просто цитируй; "
        "если человек сам пояснил или поправил («Славик это исполнитель») — верь его поправке. "
        "Без заголовков-категорий («Темы:», «Мнения:»), без пустых пунктов («нет», «нет явных») и без пометок о "
        "правке («убрано», «оставить»). Нельзя: здоровье, внешность, семья, деньги, религия, политика, ориентация. "
        "До 1000 символов — самое свежее и яркое. Цитаты копируй символ в символ. Верни только пункты."
    )
    text = await _complete(DOSSIER_SYSTEM, user, max_tokens=3000, model=EDIT_MODEL)
    # модель иногда сама оборачивает ответ в <dossier>…</dossier> — теги не храним
    text = re.sub(r"</?dossier[^>]*>", "", text)
    # только пункты: без «Исправлю опечатку…» и прочих пояснений модели
    points = [_clean_point(ln) for ln in text.splitlines() if ln.strip().startswith(("-", "•"))]
    points = [p for p in points if p]
    said = [str(m[0] if isinstance(m, (tuple, list)) else m) for m in new_messages]
    out, size = [], 0
    for p in (points or [text.strip()]):  # не больше ~1200 знаков, но целыми пунктами (было: «Dota 2 (» оборвано)
        line = scrub(_fix_quotes(p, said))
        if out and size + len(line) > 1200:
            break
        out.append(line)
        size += len(line) + 1
    return "\n".join(out)


_LABEL = re.compile(r"^[-•]\s*(?:темы и увлечения|темы|увлечения|мнения?|планы|обещания и планы|обещания|хвастовство|"
                    r"противоречи[ея]|про себя|стиль|шутка|факт)\s*:\s*", re.IGNORECASE)  # «Коронные фразы:» — оставляем
_META = re.compile(r"убрано|оставить только|оставь только|исправ|нет явных|нет актуальных|не найдено|:\s*нет\s*$|"
                   r"^\W*нет\W*$", re.IGNORECASE)


def _clean_point(line: str) -> str:
    """Пункт досье без заголовка-категории («Темы:») и без пустых/служебных («нет явных», «…убрано…»)."""
    line = line.strip()
    if _META.search(line):
        return ""
    body = _LABEL.sub("", line).lstrip("-• ").strip()
    return f"- {body[:1].upper()}{body[1:]}" if len(body) > 3 else ""


def _norm(t: str) -> str:
    return re.sub(r"\s+", " ", str(t).lower().replace("ё", "е")).strip(" .,!?…")


def _fix_quotes(line: str, said: list[str]) -> str:
    """Цитаты в досье — дословно: «пойдёт» вместо сказанного «пойду» чиним по самому сообщению."""
    import difflib

    def repl(m: re.Match) -> str:
        q = m.group(1)
        nq = _norm(q)
        if not nq or any(nq in _norm(t) for t in said):
            return m.group(0)
        best = max(said, key=lambda t: difflib.SequenceMatcher(None, nq, _norm(t)).ratio(), default="")
        if best and difflib.SequenceMatcher(None, nq, _norm(best)).ratio() >= 0.75:
            return f"«{best.strip()[:160]}»"
        return m.group(0)

    return re.sub(r"«([^«»]{3,200})»", repl, line)


