def about_looks(text: str) -> bool:
    return bool(_LOOKS.search(text or ""))


async def fix_looks(out: str) -> str:
    """Шутка про внешность — одна попытка переписать (Sonnet), иначе "" (бот промолчит)."""
    if not about_looks(out):
        return out
    unquoted = re.sub(r"«[^«»]*»", "", out)  # «жирный» в кавычках — цитата наезда, не шутка про внешность…
    if not about_looks(unquoted):  # …но переписывать её нельзя (выходила выдуманная цитата) — цитату убираем
        return re.sub(r"\s{2,}", " ", re.sub(r"«[^«»]*»\s*[—–-]?\s*", "", out)).strip(" ,—–-") or ""
    try:
        out = scrub(_clean_reply(await _complete(
            ROAST_SYSTEM,
            f"Реплика бота: <draft>{out[:600]}</draft>\nВ ней шутка про внешность (лицо, тело, вес, волосы) — "
            "это запрещено. Перепиши без неё: подколи за слова и поступки, тот же тон и мат, так же коротко."
            + _JSON_REPLY, max_tokens=1500, model=EDIT_MODEL)))
    except Exception as e:
        logger.warning("looks rewrite failed: %s", e)
        return ""
    return "" if about_looks(out) else out


def scrub(text: str) -> str:
    """Заменяет слова за красными линиями на жёсткое ругательство из словаря."""
    if not text:
        return text
    safe = [w for w in INSULTS if " " not in w] or ["мудак"]
    return _BANNED.sub(lambda m: random.choice(safe), text)


_MIXED = re.compile(r"[а-яё][a-z]|[a-z][а-яё]", re.IGNORECASE)


def _garbled(text: str) -> bool:
    """Слово, склеенное из кириллицы и латиницы («еблаor») — признак сбоя модели."""
    return bool(_MIXED.search(text or ""))


_TAIL = re.compile(r"(?<!\bиди)(?<!пошёл)(?<!пошел)(?<!пошла)(?<!пошли)(?<!вали)(?<!катись)(?<!пиздуй)"
                   r"[,\s]+(?:нахуй|нахер|нахрен|блядь|блять|бля)\s*([.!?…]*)\s*$", re.IGNORECASE)


def drop_tail_filler(text: str) -> str:
    """«…розетку найди нахуй» → «…розетку найди»: мат, прицепленный в конец по привычке (кроме «иди нахуй»)."""
    out = text or ""
    for _ in range(2):
        new = _TAIL.sub(lambda m: m.group(1), out).rstrip(" ,")
        if new == out:
            break
        out = new
    return out if len(out.split()) >= 3 else text


async def polish(reply: str, trigger: str, context: list[dict] | None = None,
                 max_words: int = 20, author: str = "", about_photo: bool = False,
                 long_form: bool = False, image: tuple[bytes, str] | None = None, seen: str = "") -> str:
    """Финальная проверка реплики перед отправкой — БЕЗ второго ИИ-«редактора» (он выравнивал все ответы под
    один шаблон и искажал смысл): мусор, красные линии, передразнивание, пересказ фото, внешность, длина.
    Возвращает реплику или "" (не слать). Аргументы context/about_photo/image — для совместимости вызовов."""
    del context, about_photo, image
    out = (reply or "").strip()
    if not out or _garbled(out):  # сбой модели вроде «еблаor» — лучше промолчать
        return ""
    out = scrub(drop_echo(out, trigger))
    out = drop_tail_filler(out)
    if "»" in out and ("«" not in out or out.index("»") < out.index("«")):  # «тупой как пробка» без «
        out = "«" + out
    seen = seen or _seen_from(trigger)
    if out and seen and retells(out, seen):  # «чипсы, пирожки и кола — …» — пересказ фото, переписываем
        logger.info("reply retells the picture, rewriting: %s", out)
        try:
            out = scrub(await drop_retell(out, seen, author, max_words=max_words))
        except Exception as e:
            logger.warning("drop_retell failed: %s", e)
    out = await fix_looks(out)
    words = out.split()
    limit = max_words * (4 if long_form else 2)
    if len(words) > limit:  # страховка от простыни
        cut = re.split(r"(?<=[.!?…])\s+", out)
        out = cut[0] if cut and len(cut[0].split()) <= limit else " ".join(words[:limit]) + "…"
    return out


