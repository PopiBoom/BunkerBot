# имя функции ai.py, из которой пошёл запрос, мимо обёрток. В /admin → «💰 Расходы ИИ» — разбивка по ним.
_KIND_SKIP = {"_kind", "_record", "_complete", "complete_any", "speak", "_speak_long", "say", "eleven", "yandex", "gpt",
              "_eleven_once", "eleven_speak", "_eleven_bytes", "_complete_openrouter"}


def _kind() -> str:
    import sys

    f = sys._getframe(1)
    while f is not None and (f.f_code.co_name in _KIND_SKIP or f.f_code.co_name.startswith("<")):
        f = f.f_back
    return f.f_code.co_name if f is not None else "?"


def price(model: str, input_tokens: int, output_tokens: int) -> float:
    pin, pout = PRICES.get(model, PRICES.get(MODEL, (4.0, 20.0)))
    return (input_tokens * pin + output_tokens * pout) / 1_000_000


class AIUnavailable(RuntimeError):
    """Ведущий не настроен или недоступен."""


def _get_client() -> AsyncAnthropic:
    global _client
    if _client is None:
        api_key = os.getenv("ANTHROPIC_API_KEY", "").strip()
        if not api_key:
            raise AIUnavailable("ANTHROPIC_API_KEY не задан")
        # 5 минут на запрос (по умолчанию в SDK — 10): зависший запрос не должен держать партию полчаса
        _client = AsyncAnthropic(api_key=api_key, timeout=300.0, max_retries=2)
    return _client


def available() -> bool:
    return bool(os.getenv("ANTHROPIC_API_KEY", "").strip())


def _extract_json(text: str) -> dict:
    text = text.strip()
    fence = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", text, re.DOTALL)
    if fence:
        return json.loads(fence.group(1))
    start = text.find("{")
    end = text.rfind("}")
    if start != -1 and end != -1 and end > start:
        return json.loads(text[start : end + 1])
    return json.loads(text)


