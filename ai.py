def vary_father(text: str) -> str:
    """Не начинать каждый ответ бате с «бать»: если недавно уже начинали — обращение убираем."""
    if not text or not _FATHER_ADDR.match(text):
        return text
    recent = recent_bot_lines.get() or []
    used = sum(1 for t in recent[-6:] if _FATHER_ADDR.match(t or ""))
    if used == 0 and random.random() < 0.5:  # давно не называл — можно и оставить
        return text
    rest = _FATHER_ADDR.sub("", text, count=1).strip()
    return (rest[:1].upper() + rest[1:]) if rest else text


_MAT_WORD = re.compile(r"(?:ху[йеёияюл]|пизд|[её]б[аеиоуыё]|бля|заеб|наеб|уеб|муд[аои]|сук[аи]|херн|нахер)", re.IGNORECASE)


def worn_out(lines: list[str]) -> tuple[set[str], set[str], set[str]]:
    """Что бот уже затёр в последних репликах: (мат-слова в 3+ репликах, первые слова 2+ раз, последние 2+ раз).
    По логу владельца: «ебать…» в начале, «пиздец» внутри и «нахуй» в конце почти каждого ответа."""
    from collections import Counter

    words, firsts, lasts = Counter(), Counter(), Counter()
    for t in lines[-8:]:
        toks = re.findall(r"[а-яё]+", str(t).lower().replace("ё", "е"))
        if not toks:
            continue
        words.update({w for w in toks if _MAT_WORD.search(w)})
        firsts[toks[0]] += 1
        lasts[toks[-1]] += 1
    return ({w for w, n in words.items() if n >= 3}, {w for w, n in firsts.items() if n >= 2},
            {w for w, n in lasts.items() if n >= 2})


def _variety() -> str:
    """Свои последние реплики (не повторяться), запрет затёртого и щепотка словаря — приправа, а не правила."""
    words = ", ".join(random.sample(INSULTS, 4))
    phrases = "; ".join(random.sample(MAT_PHRASES, 3))
    recent = recent_bot_lines.get() or []
    avoid = "\n".join(f"<said>{t[:160]}</said>" for t in recent[-10:])
    mat, firsts, lasts = worn_out(list(recent))
    ban = []
    if mat:
        ban.append("слова " + ", ".join(f"«{w}»" for w in sorted(mat)))
    if firsts:
        ban.append("начинать со слова " + " или ".join(f"«{w}»" for w in sorted(firsts)))
    if lasts:
        ban.append("заканчивать словом " + " или ".join(f"«{w}»" for w in sorted(lasts)))
    return (
        f"\nЕсли к месту — можно взять из словаря: {words}; {phrases} (… — подставь своё). Не «лошара»."
        + (f"\nЗАТЁРТО, в этот раз НЕЛЬЗЯ: {'; '.join(ban)} — возьми другие слова и другое построение." if ban else "")
        + (f"\nТвои последние реплики — не повторяй их слова, шутки и построение:\n{avoid}" if avoid else "")
    )


