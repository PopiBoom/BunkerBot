def command_name(text: str) -> str | None:
    """«/roast@pizdyuk_bot @вася» → «roast»; не команда → None."""
    if not text or not text.startswith("/"):
        return None
    return text.split()[0][1:].split("@")[0].lower() or None


def menu(sections, separators: bool = False) -> list[tuple[str, str]]:
    """[(команда, описание для меню)]. Обычно — эмодзи раздела в начале описания; separators=True —
    перед каждым разделом строка-заголовок «━━ 🕵️ МАФИЯ ━━», а у команд описание без эмодзи."""
    out = []
    for title, items in sections:
        emoji = title.split()[0]
        sep = separators and title in SEPARATORS
        if sep:
            out.append((SEPARATORS[title], f"━━ {title.upper()} ━━"))
        for cmd, short, _long in items:  # под разделителем — без эмодзи, иначе (и у «Меню») — с ним
            out.append((cmd, (short if sep else f"{emoji} {short}")[:256]))
    return out


def help_text(sections) -> str:
    """HTML для /help: разделы, команды и подробности."""
    import html

    parts = ["📖 <b>КОМАНДЫ ПИЗДЮКА</b>", "━━━━━━━━━━━━━━━"]
    for title, items in sections:
        parts.append(f"\n<b>{html.escape(title)}</b>")
        for cmd, _short, long in items:
            parts.append(f"/{cmd} — {html.escape(long)}")
    parts.append("\n<i>Подсказка: набери «/» — команды появятся в меню.</i>")
    return "\n".join(parts)
